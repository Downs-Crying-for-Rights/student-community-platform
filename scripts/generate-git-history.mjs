import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const ref = process.argv[2] || "HEAD";
const separator = "\u001f";
const recordSeparator = "\u001e";
const format = ["%H", "%h", "%cI", "%an", "%s", "%P"].join("%x1f") + "%x1e";
const output = execFileSync("git", [
  "log",
  ref,
  "--reverse",
  "--date-order",
  `--pretty=format:${format}`,
], { encoding: "utf8", maxBuffer: 20 * 1024 * 1024 });

function classify(subject, parents) {
  if (parents.trim().split(/\s+/).filter(Boolean).length > 1 || /^Merge\b/i.test(subject)) return "merge";
  const prefix = subject.match(/^([a-z]+)(?:\([^)]*\))?:/i)?.[1]?.toLowerCase();
  if (["feat", "fix", "test", "ci", "build", "docs", "refactor", "chore", "perf", "revert"].includes(prefix)) return prefix;
  return "other";
}

const commits = output
  .split(recordSeparator)
  .map((record) => record.trim())
  .filter(Boolean)
  .map((record) => {
    const [hash, shortHash, committedAt, authorName, subject, parents] = record.split(separator);
    return {
      hash,
      shortHash,
      committedAt,
      authorName,
      subject,
      type: classify(subject, parents || ""),
      version: subject.match(/^build: bump version to v(.+)$/)?.[1] || null,
      isMerge: (parents || "").trim().split(/\s+/).filter(Boolean).length > 1,
    };
  })
  .sort((left, right) => Date.parse(left.committedAt) - Date.parse(right.committedAt) || left.hash.localeCompare(right.hash));

const sourceCommit = execFileSync("git", ["rev-parse", ref], { encoding: "utf8" }).trim();
const content = `// Generated by scripts/generate-git-history.mjs. Do not edit manually.\n`
  + `export const GIT_HISTORY_SOURCE_COMMIT = ${JSON.stringify(sourceCommit)};\n`
  + `export const GIT_HISTORY = ${JSON.stringify(commits, null, 2)} as const;\n`;

writeFileSync(resolve("src/lib/git-history.generated.ts"), content, "utf8");
console.log(`Generated ${commits.length} commits through ${sourceCommit}.`);
